#!/usr/bin/env node
// Classifies names into Short (1-4 letters), Medium (5-6 letters), Long (7+ letters)
// Produces data/experiments/by-name-length/boys.json and girls.json

const fs = require('fs');
const path = require('path');

const dataDir = path.join(__dirname, '..', '..', 'data');
const outputDir = path.join(__dirname, '..', '..', 'experiment-data', 'by-name-length');

function loadData(gender) {
  const devPath = path.join(dataDir, `${gender}-dev.json`);
  const prodPath = path.join(dataDir, `${gender}.json`);
  if (fs.existsSync(devPath)) {
    console.log(`Using dev data for ${gender}`);
    return JSON.parse(fs.readFileSync(devPath, 'utf-8'));
  }
  return JSON.parse(fs.readFileSync(prodPath, 'utf-8'));
}

function classifyByLength(name) {
  const len = name.length;
  if (len <= 4) return 'Short (1-4 letters)';
  if (len <= 6) return 'Medium (5-6 letters)';
  return 'Long (7+ letters)';
}

function generateClassification(names) {
  const classes = {};
  names.forEach(nameObj => {
    const className = classifyByLength(nameObj.name);
    if (!classes[className]) classes[className] = [];
    classes[className].push(nameObj.name);
  });
  Object.keys(classes).forEach(k => classes[k].sort());
  return classes;
}

fs.mkdirSync(outputDir, { recursive: true });

const boysData = loadData('boys');
const girlsData = loadData('girls');

const boysClasses = generateClassification(boysData);
const girlsClasses = generateClassification(girlsData);

fs.writeFileSync(path.join(outputDir, 'boys.json'), JSON.stringify(boysClasses, null, 2));
fs.writeFileSync(path.join(outputDir, 'girls.json'), JSON.stringify(girlsClasses, null, 2));

console.log('\nGenerated by-name-length experiment data:');
Object.entries(boysClasses).forEach(([k, v]) => console.log(`  Boys - ${k}: ${v.length} names`));
Object.entries(girlsClasses).forEach(([k, v]) => console.log(`  Girls - ${k}: ${v.length} names`));
